<?php

declare(strict_types=1);

namespace App\Errors;

use Pin\Errors\Errorful;
use Pin\Errors\IError;

/**
 * 枚举：系统错误码定义
 *
 * 约定：
 * - 所有错误码 >= 10000
 * - 格式：code|message|statusCode
 * - code：唯一业务错误码（用于前端判断 / 日志追踪）
 * - message：默认错误提示（可直接返回给用户）
 *
 * 分段规则：
 * - 10000 ~ 19999：通用错误
 * - 20000 ~ 29999：用户相关
 *   - 21000 ~ 21999：登录相关
 *
 * 使用建议：
 * - 错误码用于程序判断，不要依赖 message
 * - message 可根据业务进行国际化替换
 */
enum Errors: string implements IError
{
    use Errorful;

    /*
    |--------------------------------------------------------------------------
    | 通用错误：10000 -
    |--------------------------------------------------------------------------
    */

    /*
    |--------------------------------------------------------------------------
    | 用户模块：20000 -
    |--------------------------------------------------------------------------
    */

    /*
    |--------------------------------------------------------------------------
    | 登录相关：21000 -
    |--------------------------------------------------------------------------
    */
    /**
     * 登录失败：统一返回模糊错误，避免账号枚举攻击
     */
    case LoginFailed = '21000|帐号或密码错误';
    /**
     * 登录失败：用户不存在（用于日志）
     */
    case LoginAccountNotFound = '21001|帐号或密码错误';
    /**
     * 登录失败：密码错误（用于日志）
     */
    case LoginPasswordMismatch = '21002|帐号或密码错误';
}
